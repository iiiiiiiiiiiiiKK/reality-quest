/**
 * Curated real landmarks.
 *
 * Why this exists
 * ---------------
 * Overpass is a free, rate-limited public service. When it is slow, busy or
 * blocked by a network, a quest app that depends on it alone becomes an empty
 * map — a broken product. This module is the offline floor: a hand-curated set
 * of *real* places with real WGS84 coordinates, shipped with the app.
 *
 * These are explicitly labelled `source: 'curated'` in the UI ("selected real
 * landmark"), so nothing pretends to be live OSM data. No coordinate here is
 * generated; each is a place you can actually stand in front of.
 */

