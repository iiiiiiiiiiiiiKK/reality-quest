const ROMAN: Record<Difficulty, string> = { easy: 'I', normal: 'II', hard: 'III', epic: 'IV' };

/** Deterministic quest built from a curated place. */
export function curatedToQuest(place: CuratedPlace): Quest {
  return {
    id: `curated-${place.id}`,
    title: { zh: `探索${place.nameZh}`, en: `Explore ${place.nameEn}` },
    description: { zh: place.hookZh, en: place.hookEn },
    category: place.category,
    lat: place.lat,
    lng: place.lng,
    radius: RADIUS_BY_DIFFICULTY[place.difficulty],
    difficulty: place.difficulty,
    xp: xpForDifficulty(place.difficulty),
    estimatedMinutes: place.difficulty === 'epic' ? 60 : place.difficulty === 'hard' ? 35 : 18,
    requiresPhoto: place.category === 'photo',
    source: 'curated',
    creator: 'Reality Quest curated',
    createdAt: 0,
    isPublic: true,
    placeName: `${place.nameZh} / ${place.nameEn}`,
    sourceUrl: `https://www.openstreetmap.org/#map=17/${place.lat}/${place.lng}`,
  };
}

/**
 * Curated places near a coordinate, nearest first. Used as the offline floor
 * when Overpass returns nothing or is unreachable.
 */
export function nearestCurated(
  lat: number,
  lng: number,
  radiusKm = 40,
  limit = 40,
): CuratedPlace[] {
  const origin = { lat, lng };
  return CURATED_PLACES.map((place) => ({ place, d: haversineMeters(origin, place) }))
    .filter((row) => row.d <= radiusKm * 1000)
    .sort((a, b) => a.d - b.d)
    .slice(0, limit)
    .map((row) => row.place);
}

/** Nearest curated city to a coordinate — used to suggest where to look. */
export function nearestCuratedCity(lat: number, lng: number): CuratedPlace | undefined {
  return CURATED_PLACES.map((place) => ({ place, d: haversineMeters({ lat, lng }, place) })).sort(
    (a, b) => a.d - b.d,
  )[0]?.place;
}

export const CURATED_CITIES = Array.from(
  new Map(
    CURATED_PLACES.map((p) => [
      p.cityEn,
      { cityZh: p.cityZh, cityEn: p.cityEn, lat: p.lat, lng: p.lng, count: 0 },
    ]),
  ).values(),
).map((city) => {
  const count = CURATED_PLACES.filter((p) => p.cityEn === city.cityEn).length;
  return { ...city, count };
});

