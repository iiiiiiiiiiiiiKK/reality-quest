export const messages: Record<Lang, Dict> = { zh, en };

export type TranslateVars = Record<string, string | number>;

export function translate(lang: Lang, key: string, vars?: TranslateVars): string {
  const raw = messages[lang][key] ?? messages.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function pickLang(text: { zh: string; en: string } | undefined, lang: Lang): string {
  if (!text) return '';
  return (lang === 'zh' ? text.zh : text.en) || text.en || text.zh || '';
}

export function formatDate(ts: number, lang: Lang): string {
  const d = new Date(ts);
  if (Number.isNaN(d.getTime())) return '\u2014';
  return new Intl.DateTimeFormat(lang === 'zh' ? 'zh-CN' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(d);
}
